# ============================================================================
# ЗАВДАННЯ 1
# ============================================================================
print("\n" + "="*80)
print("ЗАВДАННЯ 1: Визначення втрат при поширенні")
print("="*80)

# ---------------- ВИХІДНІ ДАНІ ----------------
lambda_m = 104       # м
r_m = 107            # м
D1_abs = 100
D2_abs = 100
F_dB = -50

print("\n--- ВИХІДНІ ДАНІ ---")
print(f"λ = {lambda_m} м")
print(f"r = {r_m} м")
print(f"D₁ = D₂ = {D1_abs}")
print(f"F = {F_dB} дБ")

# Переведення в дБ
D1_dB = 10 * math.log10(D1_abs)
D2_dB = 10 * math.log10(D2_abs)
F_abs = 10 ** (F_dB / 20)

# ---------------- 1. ОСНОВНІ ВТРАТИ ----------------
print("\n--- 1. ОСНОВНІ ВТРАТИ (L_осн) ---")
L_osn = ((4 * math.pi * r_m) / (lambda_m * F_abs)) ** 2
L_osn_dB = 20 * math.log10((4 * math.pi * r_m) / lambda_m) + abs(F_dB)

print(f"L_осн = {L_osn:.4e}")
print(f"L_осн = {L_osn_dB:.2f} дБ")

# ---------------- 2. ВТРАТИ У ВІЛЬНОМУ ПРОСТОРІ ----------------
print("\n--- 2. ВТРАТИ У ВІЛЬНОМУ ПРОСТОРІ (L_св) ---")
L_sv = ((4 * math.pi * r_m) / lambda_m) ** 2
L_sv_dB = 20 * math.log10((4 * math.pi * r_m) / lambda_m)

print(f"L_св = {L_sv:.4e}")
print(f"L_св = {L_sv_dB:.2f} дБ")

# ---------------- 3. ЗАГАЛЬНІ ВТРАТИ ----------------
print("\n--- 3. ЗАГАЛЬНІ ВТРАТИ (L_заг) ---")
L_total = L_sv / (D1_abs * D2_abs * F_abs**2)
L_total_dB = L_sv_dB - D1_dB - D2_dB + abs(F_dB)

print(f"L_заг = {L_total:.4e}")
print(f"L_заг = {L_total_dB:.2f} дБ")

# ============================================================================
# ЗАВДАННЯ 2
# ============================================================================
print("\n\n" + "="*80)
print("ЗАВДАННЯ 2: Визначення потужності на вході приймача")
print("="*80)

# ---------------- ВИХІДНІ ДАНІ ----------------
P1_dBW = 20          # дБВт
r2_km = 300
r2_m = r2_km * 1000
lambda_2_m = 0.30    # 30 см
F2_dB = -60
D1_2_dB = 20
D2_2_dB = 20

print("\n--- ВИХІДНІ ДАНІ ---")
print(f"P₁ = {P1_dBW} дБВт")
print(f"r = {r2_km} км")
print(f"λ = {lambda_2_m} м")
print(f"F = {F2_dB} дБ")
print(f"D₁ = D₂ = {D1_2_dB} дБ")

# Переведення в абсолютні одиниці
P1_W = 10 ** (P1_dBW / 10)
D1_2_abs = 10 ** (D1_2_dB / 10)
D2_2_abs = 10 ** (D2_2_dB / 10)
F2_abs = 10 ** (F2_dB / 10)

# ---------------- ОБЧИСЛЕННЯ P₂ ----------------
print("\n--- ОБЧИСЛЕННЯ ПОТУЖНОСТІ P₂ ---")

P2_W = (P1_W * D1_2_abs * D2_2_abs *
        (lambda_2_m ** 2) * F2_abs) / ((4 * math.pi * r2_m) ** 2)

P2_dBW = 10 * math.log10(P2_W)
P2_dBm = P2_dBW + 30

print(f"P₂ = {P2_W:.4e} Вт")
print(f"P₂ = {P2_dBW:.2f} дБВт")
print(f"P₂ = {P2_dBm:.2f} дБм")

